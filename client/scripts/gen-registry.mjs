/**
 * Writes src/config/features.generated.ts by scanning src/features/*.
 * That is why "remove a feature" = delete its folder + one config line:
 * nothing hand-written imports a feature, this generated list does (and it is rebuilt on every dev/build).
 * Folders starting with "_" (like _template) are skipped.
 */
import { readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');
const dir = join(root, 'features');
const ids = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith('_') && existsSync(join(dir, d.name, 'index.ts')))
  .map((d) => d.name)
  .sort();

const ident = (id) => id.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const out = `// AUTO-GENERATED by scripts/gen-registry.mjs. Do not edit by hand.
import type { FeatureManifest } from '@/core/types';
${ids.map((id) => `import ${ident(id)} from '@/features/${id}';`).join('\n')}

export const manifests: FeatureManifest[] = [${ids.map(ident).join(', ')}];
`;
writeFileSync(join(root, 'config', 'features.generated.ts'), out);
console.log(`[registry] ${ids.length} feature(s): ${ids.join(', ')}`);
